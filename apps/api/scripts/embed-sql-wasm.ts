import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

/**
 * Embeds the sql.js WASM binary as a base64 TypeScript module so the runtime
 * needs no filesystem resolution (Vercel serverless functions don't bundle the
 * `.wasm` file). Run with `bun run build:wasm` after upgrading `sql.js`.
 */
const require = createRequire(import.meta.url);
const wasm = readFileSync(require.resolve("sql.js/dist/sql-wasm.wasm"));

const contents = `// Generated by \`bun run build:wasm\`. Do not edit by hand.
export const sqlWasmBase64 =
  "${wasm.toString("base64")}";
`;

writeFileSync(new URL("../src/data/sql-wasm.ts", import.meta.url), contents);
console.log(
  `Embedded sql.js wasm (${wasm.length} bytes) -> src/data/sql-wasm.ts`,
);
