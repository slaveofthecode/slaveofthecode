import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { getContent } from "@portfolio/content";
import type { AppConfig } from "../../config.js";
import { loadConfig } from "../../config.js";
import type { EmbeddingProvider } from "../../domain/embedding-provider.js";
import { buildChunks } from "../../domain/rag.js";
import { GeminiEmbeddings } from "../llm/gemini-embeddings.js";
import { CV_PATH, RAG_DB_MODULE_PATH, SNAPSHOT_PATH } from "./paths.js";
import { type RagMeta, type RagRecord, buildRagBytes } from "./sqlite-store.js";

async function embedAll(config: AppConfig): Promise<RagRecord[]> {
  const embeddings: EmbeddingProvider = new GeminiEmbeddings(config.gemini);
  const chunks = buildChunks(getContent());
  const vectors = await embeddings.embed(chunks.map((chunk) => chunk.content));
  console.log(`embedded ${chunks.length} chunks`);
  return chunks.map((chunk, index) => ({
    ...chunk,
    embedding: vectors[index] ?? [],
  }));
}

export async function buildRagSnapshot(
  options: { empty?: boolean } = {},
): Promise<void> {
  const config = loadConfig();
  const records = options.empty ? [] : await embedAll(config);
  const meta: RagMeta = {
    cvSha256: createHash("sha256").update(readFileSync(CV_PATH)).digest("hex"),
    embeddingModel: config.gemini.embedModel,
    builtAt: new Date().toISOString(),
  };
  const bytes = await buildRagBytes(records, meta);

  mkdirSync(dirname(SNAPSHOT_PATH), { recursive: true });
  writeFileSync(SNAPSHOT_PATH, bytes);

  const base64 = Buffer.from(bytes).toString("base64");
  writeFileSync(
    RAG_DB_MODULE_PATH,
    `// AUTO-GENERATED by \`bun run build:rag\`. Do not edit by hand.\nexport const ragDbBase64 =\n  "${base64}";\n`,
  );

  console.log(
    `Wrote ${records.length} chunks (${bytes.length} bytes) for cv.json ${meta.cvSha256} -> data/cv.sqlite + src/data/rag-db.ts`,
  );
}
